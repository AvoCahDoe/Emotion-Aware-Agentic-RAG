"""Run eval queries against a live API and refresh comparison_results.md."""

from __future__ import annotations

import argparse
import json
import urllib.error
import urllib.request
from collections import defaultdict
from pathlib import Path


EVAL_DIR = Path(__file__).resolve().parent
QUERIES_PATH = EVAL_DIR / "queries.json"
OUT_PATH = EVAL_DIR / "comparison_results.md"


def post_query(api: str, query: str) -> dict:
    req = urllib.request.Request(
        f"{api.rstrip('/')}/query",
        data=json.dumps({"query": query}).encode("utf-8"),
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    with urllib.request.urlopen(req, timeout=120) as resp:
        return json.loads(resp.read().decode("utf-8"))


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--api", default="http://localhost:8000")
    args = parser.parse_args()

    queries = json.loads(QUERIES_PATH.read_text(encoding="utf-8"))
    by_base: dict[str, list[dict]] = defaultdict(list)

    for item in queries:
        try:
            result = post_query(args.api, item["query"])
            expl = result.get("explainability", {})
            answer = (result.get("answer") or "").replace("\n", " ").strip()
            if len(answer) > 180:
                answer = answer[:177] + "..."
            by_base[item["base_id"]].append(
                {
                    **item,
                    "emotion": expl.get("emotion", "?"),
                    "confidence": expl.get("confidence", "?"),
                    "strategy": expl.get("strategy", "?"),
                    "answer": answer,
                }
            )
            print(f"OK  {item['id']} → {expl.get('strategy')}")
        except (urllib.error.URLError, TimeoutError, json.JSONDecodeError) as exc:
            print(f"ERR {item['id']}: {exc}")
            by_base[item["base_id"]].append({**item, "emotion": "error", "confidence": "-", "strategy": "-", "answer": str(exc)})

    lines = [
        "# Emotion-aware strategy comparison",
        "",
        "Generated by `python -m eval.run_comparison`.",
        "",
        "| Base intent | Framing | Detected emotion | Conf. | Strategy | Answer (truncated) |",
        "|---|---|---|---|---|---|",
    ]
    for base_id, rows in by_base.items():
        for row in rows:
            lines.append(
                f"| {base_id} | {row['emotion_framing']} | {row.get('emotion')} | "
                f"{row.get('confidence')} | {row.get('strategy')} | {row.get('answer')} |"
            )
    lines.extend(
        [
            "",
            "## Reproduce",
            "",
            "```bash",
            "cd backend",
            "python -m eval.run_comparison --api http://localhost:8000",
            "```",
            "",
        ]
    )
    OUT_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT_PATH}")


if __name__ == "__main__":
    main()
